export function getAwsDomain(slug: string) {
  if (slug === 'compare') {
    return {
      slug: 'compare',
      name: 'Compare',
      nameZh: '高频易混淆',
      description: '集中比较用途相近、名称相近或考试中经常同时出现的服务。',
      icon: 'compare',
      tone: 'orange',
      services: ['SG vs NACL', 'S3 vs EBS vs EFS', 'ALB vs NLB'],
    } satisfies AwsDomain;
  }

  return awsDomains.find((domain) => domain.slug === slug);
}
